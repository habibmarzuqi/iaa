const DICTS: Record<Locale, Dict> = { id: ID, en: EN }

export function useTranslation() {
  const locale = useI18n((s) => s.locale)
  const t = React.useCallback(
    (key: string, fallback?: string): string => {
      return DICTS[locale]?.[key] ?? fallback ?? key
    },
    [locale]
  )
  return { t, locale }
}
